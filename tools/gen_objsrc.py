#!/usr/bin/env python3
"""Object system sources for the object-enabled builds (demo, harness_obj).

The decomp's object code is compiled as is, except that it is cut down to the
behaviors the demo uses, so it fits the GBA:

- object_list_processor.c, object_helpers.c, obj_behaviors.c and
  obj_behaviors_2.c are copied with only the whitelisted behaviors/*.inc.c
  includes kept, next to a copy of object_list_processor.h whose
  OBJECT_POOL_CAPACITY is smaller (240 objects are 146 KB; the GBA has 256 KB);
- behavior_data_subset.c holds the whitelisted scripts from data/behavior_data.c,
  verbatim;
- bhv_dummies_obj.c defines every other behavior as a script that deactivates
  the object at once, so code that spawns one (particles, effects not ported
  yet) runs safely and the slot is freed the same frame.

    tools/gen_objsrc.py DECOMP OUTDIR
"""
import os
import re
import sys

POOL_CAPACITY = 40

# behaviors/*.inc.c kept, by the file that includes them
INCLUDES = {
    "obj_behaviors.c": ["bobomb", "explosion", "corkbox"],  # corkbox: the respawner
    "obj_behaviors_2.c": ["goomba"],
    "object_helpers.c": [],
    "object_list_processor.c": [],
}

# scripts compiled from data/behavior_data.c
SCRIPTS = [
    "bhvGoomba", "bhvGoombaTripletSpawner",
    "bhvBobomb", "bhvBobombFuseSmoke", "bhvExplosion", "bhvRespawner",
]


# Mario as an object, updated by the harness's step (src/obj/objects.c):
# bhvMario's setup, without its particle spawning and debug hooks.
MARIO_SCRIPT = """
void harness_mario_update(void);

const BehaviorScript bhvHarnessMarioScript[] = {
    BEGIN(OBJ_LIST_PLAYER),
    SET_INT(oIntangibleTimer, 0),
    OR_INT(oFlags, OBJ_FLAG_0100),
    OR_INT(oUnk94, 0x0001),
    SET_HITBOX(/*Radius*/ 37, /*Height*/ 160),
    BEGIN_LOOP(),
        CALL_NATIVE(harness_mario_update),
    END_LOOP(),
};
"""


def filter_includes(src, keep):
    out = []
    for line in src.splitlines(True):
        m = re.match(r'\s*#include "behaviors/([a-z0-9_]+)\.inc\.c"', line)
        if m and m.group(1) not in keep:
            continue
        out.append(line)
    return "".join(out)


def extract_scripts(data, names):
    blocks = []
    for n in names:
        m = re.search(r"^const BehaviorScript %s\[\] = \{.*?^\};\n" % re.escape(n), data, re.S | re.M)
        if not m:
            sys.exit("gen_objsrc: script %s not found" % n)
        blocks.append(m.group(0))
    return blocks


def main():
    decomp, out = sys.argv[1], sys.argv[2]
    game = os.path.join(decomp, "src", "game")
    os.makedirs(out, exist_ok=True)

    def write(name, text):
        path = os.path.join(out, name)
        if not os.path.exists(path) or open(path).read() != text:
            open(path, "w").write(text)

    for name, keep in INCLUDES.items():
        src = open(os.path.join(game, name)).read()
        write("g_" + name, "/* Generated by tools/gen_objsrc.py from the decomp's src/game/%s */\n" % name
              + filter_includes(src, keep))
    hdr = open(os.path.join(game, "object_list_processor.h")).read()
    hdr, n = re.subn(r"#define OBJECT_POOL_CAPACITY \d+", "#define OBJECT_POOL_CAPACITY %d" % POOL_CAPACITY, hdr)
    assert n == 1
    write("object_list_processor.h", hdr)

    data = open(os.path.join(decomp, "data", "behavior_data.c")).read()
    head = data[:data.index("const BehaviorScript ")]
    write("behavior_data_subset.c", "/* Generated by tools/gen_objsrc.py: scripts from the decomp's\n"
          " * data/behavior_data.c */\n" + head + "\n".join(extract_scripts(data, SCRIPTS)) + MARIO_SCRIPT)

    names = re.findall(r"extern const BehaviorScript (\w+)\[\];",
                       open(os.path.join(decomp, "include", "behavior_data.h")).read())
    seen = set()
    lines = ["/* Generated by tools/gen_objsrc.py: behaviors not ported, deactivated on spawn. */",
             "#include <PR/ultratypes.h>", "#include \"types.h\"", ""]
    for n in names:
        if n not in SCRIPTS and n not in seen:
            seen.add(n)
            lines.append("const BehaviorScript %s[2] = { 0x1D000000, 0x0A000000 }; /* DEACTIVATE, BREAK */" % n)
    write("bhv_dummies_obj.c", "\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
